"""Satyapan Forensic Lab contracts: what every analyzer returns and what the API, the dashboard
and the court report consume.

Vocabulary (docs/forensics/METHODOLOGY.md):

* A **technique** is one forensic method (Error Level Analysis, ENF, a deepfake model ...).
  It returns a `TechniqueResult` with a status, a one-line summary, chart data, artifacts
  (heatmaps, spectrograms) and zero or more findings.
* A **finding** is one observation that supports a **hypothesis** (synthetic, manipulated,
  authentic) with an ordinal **strength** on the ENFSI-style verbal scale (weak ... very
  strong), or is purely informational (NEUTRAL).
* The **verdict** is computed from the findings by a fixed, documented rule table
  (`satyapan.forensics.verdict`), never by a model alone, and always says what could not be
  checked.
"""

from __future__ import annotations

from datetime import UTC, datetime
from enum import IntEnum, StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

ENGINE_VERSION = "1.0.0"


def utcnow() -> datetime:
    return datetime.now(UTC)


class LabModel(BaseModel):
    model_config = ConfigDict(extra="forbid", use_enum_values=False)


class MediaKind(StrEnum):
    IMAGE = "image"
    AUDIO = "audio"
    VIDEO = "video"
    DOCUMENT = "document"
    OTHER = "other"


class Category(StrEnum):
    INTEGRITY = "integrity"  # hashes, file structure, container sanity
    METADATA = "metadata"  # EXIF / XMP / IPTC / container tags
    PROVENANCE = "provenance"  # source attribution: device, platform, generator, C2PA
    TAMPERING = "tampering"  # localised edits: splices, copy-move, frame edits
    SYNTHETIC = "synthetic"  # AI-generated / deepfake detectors
    CONTENT = "content"  # what is in it (speech, faces): context, not authenticity


class Hypothesis(StrEnum):
    SYNTHETIC = "synthetic"  # wholly or partly generated by AI (deepfake, TTS, diffusion)
    MANIPULATED = "manipulated"  # edited after capture (splice, clone, retouch, cut)
    AUTHENTIC = "authentic"  # an unaltered original capture
    NEUTRAL = "neutral"  # informational, no evidential weight


class Strength(IntEnum):
    """How much a finding supports its hypothesis (ENFSI verbal scale, simplified)."""

    NONE = 0
    WEAK = 1
    MODERATE = 2
    STRONG = 3
    VERY_STRONG = 4


STRENGTH_WORDS = {
    Strength.NONE: "no support",
    Strength.WEAK: "weak support",
    Strength.MODERATE: "moderate support",
    Strength.STRONG: "strong support",
    Strength.VERY_STRONG: "very strong support",
}


class Status(StrEnum):
    OK = "ok"
    SKIPPED = "skipped"  # not applicable to this file (e.g. ELA on a lossless PNG screenshot)
    UNAVAILABLE = "unavailable"  # model / dependency not installed on this workstation
    ERROR = "error"  # the technique failed on this file; never counted as "clean"


class VerdictLabel(StrEnum):
    SYNTHETIC = "SYNTHETIC"  # AI-generated / deepfake
    MANIPULATED = "MANIPULATED"  # edited after capture
    SUSPICIOUS = "SUSPICIOUS"  # indicators present, not conclusive: examine further
    NO_INDICATORS = "NO_INDICATORS"  # nothing found by the techniques that ran
    INCONCLUSIVE = "INCONCLUSIVE"  # too little could be checked


class Region(LabModel):
    """A rectangle on an image or frame, normalised to [0, 1] of width / height."""

    x: float
    y: float
    w: float
    h: float
    label: str = ""
    score: float | None = None


class TimeSpan(LabModel):
    start_s: float
    end_s: float
    label: str = ""
    score: float | None = None


class Artifact(LabModel):
    name: str  # file name under the evidence's artifact folder
    kind: str  # heatmap | overlay | chart | spectrogram | thumbnail | figure | crop
    title: str
    caption: str = ""
    media_type: str = "image/png"


class Finding(LabModel):
    code: str  # stable machine id, e.g. IMG_COPY_MOVE
    title: str
    detail: str  # plain-language explanation of what was measured and why it matters
    hypothesis: Hypothesis
    strength: Strength
    category: Category
    technique: str = ""  # filled in by the engine
    score: float | None = None
    regions: list[Region] = Field(default_factory=list)
    spans: list[TimeSpan] = Field(default_factory=list)
    artifacts: list[str] = Field(default_factory=list)
    observations: dict[str, Any] = Field(default_factory=dict)


class TechniqueResult(LabModel):
    id: str  # e.g. image.ela
    name: str
    category: Category
    status: Status
    summary: str = ""
    method: str = ""  # one paragraph for the report's methodology section
    reference: str | None = None  # citation for the method
    version: str = "1"
    duration_ms: float = 0.0
    findings: list[Finding] = Field(default_factory=list)
    artifacts: list[Artifact] = Field(default_factory=list)
    data: dict[str, Any] = Field(default_factory=dict)  # chart series, tables
    error: str | None = None
    limitations: str | None = None


class Hashes(LabModel):
    md5: str
    sha1: str
    sha256: str
    size_bytes: int


class MediaInfo(LabModel):
    kind: MediaKind
    mime: str
    format: str  # detected from the bytes (magic), not the name
    extension: str = ""
    extension_mismatch: bool = False
    width: int | None = None
    height: int | None = None
    duration_s: float | None = None
    fps: float | None = None
    sample_rate: int | None = None
    channels: int | None = None
    codec: str | None = None
    audio_codec: str | None = None
    frames: int | None = None
    has_audio: bool | None = None
    bit_depth: int | None = None
    color_mode: str | None = None


class Provenance(LabModel):
    """Best current answer to 'where did this come from', each with its evidence."""

    device: str | None = None
    software: str | None = None
    platform: str | None = None  # WhatsApp, Telegram, Facebook, screenshot ...
    generator: str | None = None  # Stable Diffusion XL, Adobe Firefly, TTS ...
    capture_time: str | None = None
    gps: dict[str, float] | None = None
    content_credentials: str | None = None  # C2PA summary
    chain: list[str] = Field(default_factory=list)  # reconstructed history, oldest first


class Verdict(LabModel):
    label: VerdictLabel
    headline: str
    statement: str  # evaluative statement in ENFSI style
    confidence: str  # verbal strength of the strongest supported hypothesis
    risk_index: int = Field(ge=0, le=100)  # dashboard gauge only; the words are authoritative
    hypotheses: dict[str, int] = Field(default_factory=dict)  # hypothesis -> max Strength
    key_findings: list[str] = Field(default_factory=list)  # finding codes, strongest first
    rationale: list[str] = Field(default_factory=list)
    not_checked: list[str] = Field(default_factory=list)  # techniques that could not run


class EvidenceAnalysis(LabModel):
    evidence_id: str
    case_id: str
    engine_version: str = ENGINE_VERSION
    started_at: datetime
    finished_at: datetime | None = None
    media: MediaInfo
    hashes: Hashes
    integrity_verified: bool
    techniques: list[TechniqueResult] = Field(default_factory=list)
    verdict: Verdict | None = None
    provenance: Provenance = Field(default_factory=Provenance)
    perceptual: dict[str, str] = Field(default_factory=dict)  # phash, dhash (images, frames)


class EvidenceRole(StrEnum):
    QUESTIONED = "questioned"  # the item under examination
    REFERENCE = "reference"  # a known sample (genuine voice, original photo) to compare with


class EvidenceStatus(StrEnum):
    QUEUED = "queued"
    ANALYZING = "analyzing"
    DONE = "done"
    ERROR = "error"


class LabEvidence(LabModel):
    id: str
    case_id: str
    exhibit: str  # court exhibit mark, e.g. "Q1" or "R1"
    filename: str
    size_bytes: int
    md5: str
    sha1: str
    sha256: str
    kind: MediaKind
    mime: str
    role: EvidenceRole = EvidenceRole.QUESTIONED
    description: str = ""
    received_from: str = ""
    received_at: datetime
    status: EvidenceStatus = EvidenceStatus.QUEUED
    verdict: VerdictLabel | None = None
    risk_index: int | None = None
    headline: str | None = None


class LabCase(LabModel):
    id: str
    title: str
    fir_number: str = ""
    police_station: str = ""
    district: str = ""
    state: str = ""
    offence_sections: str = ""
    investigating_officer: str = ""
    examiner: str = ""
    lab_name: str = "Satyapan Multimedia Forensic Lab"
    summary: str = ""
    created_at: datetime
    status: str = "open"
    demo: bool = False


class LinkKind(StrEnum):
    NEAR_DUPLICATE = "near_duplicate"  # perceptual hash close: same picture, re-encoded
    SHARES_CONTENT = "shares_content"  # a region / background is common (derived or source)
    SAME_DEVICE = "same_device"  # same camera make/model/serial in metadata
    SAME_SPEAKER = "same_speaker"  # speaker embeddings close
    SAME_FACE = "same_face"  # face embeddings close
    SAME_GENERATOR = "same_generator"  # same AI generator signature


class EvidenceLink(LabModel):
    source: str  # evidence id
    target: str
    kind: LinkKind
    score: float
    detail: str
    artifacts: list[str] = Field(default_factory=list)


class ProgressEvent(LabModel):
    evidence_id: str
    stage: str  # technique id or "intake" / "verdict" / "done"
    message: str
    progress: float  # 0..1
    at: datetime = Field(default_factory=utcnow)
    status: str = "running"  # running | ok | skipped | unavailable | error | done
