"""Draft Section 63 (Bharatiya Sakshya Adhiniyam, 2023) Certificate Generator — Parts A and B
(`src/satyapan/forensics/section63.py`).

Adapted with attribution from sibling project Pramaan (`pramaan/report/section63.py`, owner:
Saksham, task Sk9). Generates a DRAFT certificate for a human declarant and technical examiner
to verify and sign; software never certifies legal admissibility on its own.
"""

from __future__ import annotations

from typing import Any

from satyapan.forensics.locker import (
    MERKLE_SCHEME,
    ForensicEvidenceItem,
    build_merkle_proof,
    ensure_utc,
    root_for_records,
    utcnow,
)

DRAFT_BANNER = (
    "DRAFT - generated by Satyapan × Pramaan for an authorised person to verify and sign. "
    "This does not by itself make any record admissible; a court decides admissibility."
)

BLANK = "____________________"
PART_B_PROVISION = "Section 63(4)(c), Bharatiya Sakshya Adhiniyam, 2023"
HASH_STANDARD = "SHA-256 (Secure Hash Standard, FIPS PUB 180-4)"
SIGNATURE_STANDARD = "Ed25519 (EdDSA, RFC 8032; approved in FIPS 186-5)"
_IDENTIFIER_KEYS = ("serial", "imei", "hostname", "mac", "asset_tag")


def _make_model(device_info: dict[str, Any]) -> str:
    make = str(device_info.get("make", "") or "").strip()
    model = str(device_info.get("model", "") or "").strip()
    combined = (make + " " + model).strip()
    if combined:
        return combined
    os_name = str(device_info.get("os", "") or "").strip()
    return os_name if os_name else "unrecorded"


def _cell(v: Any) -> str:
    return str("" if v is None else v).replace("|", "\\|").replace("\n", " ")


def _device_schedule(evidence_items: list[ForensicEvidenceItem]) -> list[dict[str, Any]]:
    devices: dict[str, dict[str, Any]] = {}
    for item in evidence_items:
        info = dict(item.device_info or {})
        row = devices.setdefault(
            item.device,
            {
                "device": item.device,
                "make_model": "unrecorded",
                "os": "",
                "timezone": "",
                "identifiers": {},
                "collected_by_host": "",
                "record_count": 0,
            },
        )
        row["record_count"] += 1
        if row["make_model"] == "unrecorded":
            row["make_model"] = _make_model(info)
        for key in ("os", "timezone", "collected_by_host", "collector_os"):
            target_k = "os" if key == "collector_os" else key
            if not row.get(target_k) and info.get(key):
                row[target_k] = str(info[key])
        for key in _IDENTIFIER_KEYS:
            if info.get(key) and key not in row["identifiers"]:
                row["identifiers"][key] = str(info[key])
    return list(devices.values())


def _part_b(
    evidence_items: list[ForensicEvidenceItem],
    examiner: dict[str, Any],
    integrity: dict[str, Any],
) -> dict[str, Any]:
    tree = [(r["evidence_id"], r["sha256"]) for r in integrity.get("records") or []]
    if not tree:
        tree = [(i.evidence_id, i.sha256) for i in evidence_items]
    computed_root = root_for_records(tree)
    anchor_info = integrity.get("anchor") or {}
    anchored_root = anchor_info.get("merkle_root") or None
    locker_ok = integrity.get("ok")

    tree_set = set(tree)
    included = 0
    for i in evidence_items:
        if anchored_root and (i.evidence_id, i.sha256) in tree_set:
            proof = build_merkle_proof(tree, i.evidence_id)
            if proof["computed_root"] == anchored_root:
                included += 1

    return {
        "title": "Part B - Certificate of the expert (technical examiner)",
        "provision": PART_B_PROVISION,
        "examiner": {
            "name": str(examiner.get("name", "") or ""),
            "designation": str(examiner.get("designation", "") or examiner.get("role", "") or ""),
            "organisation": str(examiner.get("organisation", "") or examiner.get("lab", "") or ""),
        },
        "hash_standard": HASH_STANDARD,
        "signature_standard": SIGNATURE_STANDARD,
        "signers": list(integrity.get("signers") or []),
        "record_count": len(evidence_items),
        "merkle": {
            "scheme": MERKLE_SCHEME,
            "root": computed_root,
            "tree_size": len(tree),
            "anchored_root": anchored_root,
            "matches_anchor": (anchored_root == computed_root) if anchored_root else None,
            "records_proved": included if anchored_root else None,
        },
        "custody_chain": {
            "head": integrity.get("chain_head") or anchor_info.get("chain_head") or None,
            "entries": integrity.get("custody_entries"),
        },
        "anchor": {
            "anchor_txt": "anchor.txt",
            "anchored_at_utc": anchor_info.get("anchored_at_utc") or None,
        },
        "verification_at_generation": (
            "PASSED" if locker_ok is True else "FAILED" if locker_ok is False else "unverified"
        ),
        "tool": {
            "name": "Satyapan × Pramaan offline multimedia forensic framework",
            "network": (
                "No external network access at runtime; all deepfake, tampering, and provenance "
                "models execute locally on working copies while sealed originals remain read-only "
                "(0o444). Air-gapped operation must be confirmed by the examiner below."
            ),
        },
    }


def build_section63_certificate(
    evidence_items: list[ForensicEvidenceItem],
    declarant: dict[str, str] | None = None,
    *,
    examiner: dict[str, Any] | None = None,
    integrity: dict[str, Any] | None = None,
    generated_at_utc: str | None = None,
) -> dict[str, Any]:
    """Build Part A and Part B of the draft Section 63 BSA 2023 certificate."""
    items = list(evidence_items or [])
    decl = dict(declarant or {})
    records: list[dict[str, Any]] = []
    for item in items:
        info = dict(item.device_info or {})
        collected = ensure_utc(item.collected_at_utc).isoformat() if item.collected_at_utc else ""
        records.append(
            {
                "evidence_id": item.evidence_id,
                "file_name": item.original_name,
                "source_type": item.source_type,
                "device": item.device,
                "make_model": _make_model(info),
                "hash_algorithm": "SHA-256",
                "hash_value": item.sha256,
                "collected_at": collected,
            }
        )
    declarant_out = {
        "name": str(decl.get("name", "") or ""),
        "role": str(decl.get("role", "") or ""),
    }
    examiner_dict = dict(examiner or {})
    gen_ts = generated_at_utc or ensure_utc(utcnow()).isoformat()
    return {
        "statute": "Bharatiya Sakshya Adhiniyam, 2023 - Section 63 and the Schedule (Parts A and B)",
        "declarant": declarant_out,
        "generated_at_utc": gen_ts,
        "records": records,
        "part_a": {
            "title": (
                "Part A - Declaration by the person in charge of the device / relevant activities"
            ),
            "declarant": declarant_out,
            "devices": _device_schedule(items),
        },
        "part_b": _part_b(items, examiner_dict, dict(integrity or {})),
    }


def _render_devices(devices: list[dict[str, Any]]) -> list[str]:
    if not devices:
        return []
    lines = [
        "### Particulars of the devices involved",
        "",
        "| Device | Make / model | OS | Identifiers | Timezone | Records |",
        "|---|---|---|---|---|---|",
    ]
    for dev in devices:
        ids = dev.get("identifiers") or {}
        id_txt = "; ".join(f"{k}: {v}" for k, v in ids.items()) or "unrecorded"
        lines.append(
            "| "
            + " | ".join(
                [
                    _cell(dev.get("device")),
                    _cell(dev.get("make_model") or "unrecorded"),
                    _cell(dev.get("os") or "unrecorded"),
                    _cell(id_txt),
                    _cell(dev.get("timezone") or "unrecorded"),
                    _cell(dev.get("record_count", 0)),
                ]
            )
            + " |"
        )
    lines.append("")
    return lines


def _render_part_b(pb: dict[str, Any]) -> list[str]:
    ex = pb.get("examiner") or {}
    ex_name = str(ex.get("name", "") or "").strip() or BLANK
    ex_desig = str(ex.get("designation", "") or "").strip() or BLANK
    ex_org = str(ex.get("organisation", "") or "").strip() or BLANK
    mk = pb.get("merkle") or {}
    chain = pb.get("custody_chain") or {}
    anc = pb.get("anchor") or {}
    signers = pb.get("signers") or []
    signer_txt = (
        "; ".join(
            f"`{s.get('signer')}` (public-key SHA-256 `{s.get('public_key_sha256') or 'unavailable'}`)"
            for s in signers
        )
        or "signer key details unavailable (unverified)"
    )
    match = mk.get("matches_anchor")
    match_txt = (
        "matches the anchored root"
        if match is True
        else "DOES NOT match the anchored root"
        if match is False
        else "no anchored Merkle root was found (unverified)"
    )
    proved = mk.get("records_proved")
    proved_txt = (
        f" {proved} of {pb.get('record_count', 0)} scheduled record(s) were proved against the "
        "anchored root by their individual audit paths."
        if proved is not None
        else ""
    )
    verify = pb.get("verification_at_generation", "unverified")
    tool = pb.get("tool") or {}
    return [
        "## Section 63 (Bharatiya Sakshya Adhiniyam, 2023) - Part B Expert Certificate (DRAFT)",
        "",
        f"**Provision**: {pb.get('provision', PART_B_PROVISION)}  ",
        f"**Examiner**: {ex_name}  ",
        f"**Designation**: {ex_desig}  ",
        f"**Laboratory / organisation**: {ex_org}",
        "",
        "### Technical particulars",
        "",
        f"1. **Hash standard** - each of the {pb.get('record_count', 0)} electronic record(s) in "
        f"the Part A schedule was hashed with {pb.get('hash_standard', HASH_STANDARD)} from its "
        "sealed read-only copy at the time of intake.",
        f"2. **Digital signatures** - every custody action is a hash-chained entry signed with "
        f"{pb.get('signature_standard', SIGNATURE_STANDARD)}. Signer(s): {signer_txt}.",
        f"3. **Custody chain head** - `{chain.get('head') or 'unavailable'}` "
        f"over {chain.get('entries') if chain.get('entries') is not None else 'unknown'} entries.",
        f"4. **Merkle root anchoring** - {mk.get('scheme', MERKLE_SCHEME)}. Root over all "
        f"{mk.get('tree_size', '')} sealed record(s): `{mk.get('root', '')}`; this {match_txt}."
        f"{proved_txt} Anchored at `{anc.get('anchored_at_utc') or 'unknown'}`.",
        f"5. **Automated re-verification when this draft was generated**: {verify}.",
        f"6. **Tool operation** - {tool.get('name', 'Satyapan × Pramaan')}. "
        f"{tool.get('network', '')}",
        "",
        "### Certification by the expert",
        "",
        f"I, {ex_name}, {ex_desig}, certify under {pb.get('provision', PART_B_PROVISION)}, to the "
        "best of my knowledge and belief, that I have examined the electronic records listed in "
        "Part A; that the hash values stated were computed with the standard stated above and "
        "match the sealed copies examined by me; and that the examination was carried out:",
        "",
        "- [ ] on an air-gapped / offline workstation with no external network connection",
        "- [ ] using write-protected working copies only (sealed originals untouched at 0o444)",
        "",
        "Signature of expert: ______________________    Date: ______________________",
        "",
        f"Name: {ex_name}    Designation: {ex_desig}",
        "",
        "```",
        "+--------------------------------------+",
        "|                                      |",
        "|     OFFICIAL SEAL OF FORENSIC LAB    |",
        "|                                      |",
        "+--------------------------------------+",
        "```",
        "",
    ]


def render_section63_markdown(cert: dict[str, Any]) -> str:
    cert = cert or {}
    d = cert.get("declarant") or {}
    name = str(d.get("name", "") or "").strip() or BLANK
    role = str(d.get("role", "") or "").strip()
    who = f"{name} ({role})" if role else name
    records = cert.get("records") or []

    lines = [
        f"> **{DRAFT_BANNER}**",
        "",
        "## Section 63 (Bharatiya Sakshya Adhiniyam, 2023) - Part A Certificate (DRAFT)",
        "",
        "_Custody & device declaration by the person in charge of the device / activities._",
        "",
        f"**Generated (UTC)**: {cert.get('generated_at_utc', '')}  ",
        f"**Declarant**: {who}",
        "",
        "### Schedule of electronic records",
        "",
        "| # | Evidence ID | File name | Source type | Device | Make / model | "
        "Hash algorithm | Hash value | Collected at (UTC) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(records, 1):
        lines.append(
            "| "
            + " | ".join(
                [
                    str(i),
                    _cell(r.get("evidence_id")),
                    _cell(r.get("file_name")),
                    _cell(r.get("source_type")),
                    _cell(r.get("device")),
                    _cell(r.get("make_model")),
                    _cell(r.get("hash_algorithm")),
                    f"`{_cell(r.get('hash_value'))}`",
                    _cell(r.get("collected_at")),
                ]
            )
            + " |"
        )

    lines.append("")
    lines.extend(_render_devices((cert.get("part_a") or {}).get("devices") or []))
    lines.extend(
        [
            "### Declaration",
            "",
            f"I, {who}, state that the electronic records listed above were collected and sealed "
            "under my supervision using the Satyapan × Pramaan offline forensic framework; that "
            "the SHA-256 hash value shown for each record was computed at intake prior to parsing; "
            "and that the sealed copies have not been altered since intake.",
            "",
            "Signature: ______________________    Date: ______________________",
            "",
        ]
    )
    if cert.get("part_b"):
        lines.extend(_render_part_b(cert["part_b"]))
    lines.extend(
        [
            "### Statutory & Methodological Limitations",
            "",
            "This certificate is a DRAFT prepared by software for verification and signature by an "
            "authorised person. Software does not certify admissibility; a court decides "
            "admissibility under the Bharatiya Sakshya Adhiniyam, 2023.",
            "",
        ]
    )
    return "\n".join(lines)
