"""The verdict rule table (satyapan.forensics.verdict) and provenance assembly."""

from __future__ import annotations

from satyapan.forensics.models import (
    Category,
    Finding,
    Hypothesis,
    MediaKind,
    Status,
    Strength,
    TechniqueResult,
)
from satyapan.forensics.verdict import decide, provenance


def tech(
    tid: str, cat: Category, findings: list[Finding], status: Status = Status.OK
) -> TechniqueResult:
    for f in findings:
        f.technique = tid
    return TechniqueResult(id=tid, name=tid, category=cat, status=status, summary="s",
                           findings=findings)  # fmt: skip


def f(
    code: str, hyp: Hypothesis, s: Strength, cat: Category = Category.TAMPERING, **obs
) -> Finding:
    return Finding(code=code, title=code, detail="d", hypothesis=hyp, strength=s, category=cat,
                   observations=obs)  # fmt: skip


CLEAN = [tech("a", Category.TAMPERING, []), tech("b", Category.SYNTHETIC, [])]


def test_strong_synthetic_wins() -> None:
    v = decide(MediaKind.IMAGE, CLEAN + [tech("m", Category.SYNTHETIC,
                                              [f("X", Hypothesis.SYNTHETIC, Strength.STRONG)])])  # fmt: skip
    assert v.label.value == "SYNTHETIC" and v.confidence == "strong support" and v.risk_index == 88


def test_very_strong_or_two_strong_synthetic_is_very_strong() -> None:
    v = decide(MediaKind.IMAGE, CLEAN + [
        tech("m1", Category.SYNTHETIC, [f("X", Hypothesis.SYNTHETIC, Strength.STRONG)]),
        tech("m2", Category.PROVENANCE, [f("Y", Hypothesis.SYNTHETIC, Strength.STRONG)])])  # fmt: skip
    assert v.confidence == "very strong support" and v.risk_index == 96


def test_two_moderate_manipulation_techniques_make_manipulated() -> None:
    v = decide(MediaKind.IMAGE, CLEAN + [
        tech("ela", Category.TAMPERING, [f("E", Hypothesis.MANIPULATED, Strength.MODERATE)]),
        tech("noise", Category.TAMPERING, [f("N", Hypothesis.MANIPULATED, Strength.MODERATE)])])  # fmt: skip
    assert v.label.value == "MANIPULATED"


def test_single_moderate_is_only_suspicious() -> None:
    v = decide(MediaKind.AUDIO, CLEAN + [
        tech("splice", Category.TAMPERING, [f("S", Hypothesis.MANIPULATED, Strength.MODERATE)])])  # fmt: skip
    assert v.label.value == "SUSPICIOUS" and 50 <= v.risk_index < 70


def test_weak_findings_alone_are_not_suspicious_until_three() -> None:
    two = CLEAN + [
        tech(t, Category.METADATA, [f("W", Hypothesis.MANIPULATED, Strength.WEAK)]) for t in "xy"
    ]
    assert decide(MediaKind.IMAGE, two).label.value == "NO_INDICATORS"
    three = CLEAN + [
        tech(t, Category.METADATA, [f("W", Hypothesis.MANIPULATED, Strength.WEAK)]) for t in "xyz"
    ]
    assert decide(MediaKind.IMAGE, three).label.value == "SUSPICIOUS"


def test_too_few_checks_is_inconclusive_and_lists_what_was_not_checked() -> None:
    v = decide(MediaKind.AUDIO, [tech("a", Category.TAMPERING, []),
                                 tech("voice", Category.SYNTHETIC, [], Status.UNAVAILABLE)])  # fmt: skip
    assert v.label.value == "INCONCLUSIVE"
    assert any(x.startswith("voice") for x in v.not_checked)


def test_authentic_support_lowers_risk_but_never_says_authentic() -> None:
    v = decide(MediaKind.AUDIO, CLEAN + [
        tech("enf", Category.TAMPERING, [f("ENF_CONTINUOUS", Hypothesis.AUTHENTIC, Strength.MODERATE)])])  # fmt: skip
    assert v.label.value == "NO_INDICATORS"
    assert "does not prove" in v.statement
    assert v.risk_index <= 10


def test_neutral_findings_never_change_the_verdict() -> None:
    v = decide(MediaKind.IMAGE, CLEAN + [
        tech("meta", Category.METADATA, [f("NO_METADATA", Hypothesis.NEUTRAL, Strength.NONE)])])  # fmt: skip
    assert v.label.value == "NO_INDICATORS" and v.key_findings == []


def test_provenance_chain_orders_generator_first() -> None:
    p = provenance([
        tech("plat", Category.PROVENANCE, [f("PLATFORM_TRACE", Hypothesis.NEUTRAL, Strength.NONE,
                                             platform="WhatsApp (mobile)")]),
        tech("wm", Category.PROVENANCE, [f("SD_WATERMARK", Hypothesis.SYNTHETIC, Strength.VERY_STRONG,
                                           generator="Stable Diffusion XL")]),
    ])  # fmt: skip
    assert p.generator == "Stable Diffusion XL" and p.platform == "WhatsApp (mobile)"
    assert p.chain[0].startswith("Generated by Stable Diffusion XL")
