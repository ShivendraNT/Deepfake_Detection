def parquet_url(repo: str, split: str, n: int = 0) -> str:
    return f"https://huggingface.co/api/datasets/{repo}/parquet/default/{split}/{n}.parquet"


def fetch(url: str, dest: Path, retries: int = 6) -> Path:
    if dest.exists() and dest.stat().st_size > 0:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(".part")
    for attempt in range(retries):
        proc = subprocess.run(
            ["curl", "-sSfL", "--max-time", "300", "-o", str(tmp), url],
            capture_output=True,
            text=True,
        )
        if proc.returncode == 0:
            tmp.replace(dest)
            return dest
        time.sleep(min(90, 5 * 2**attempt))  # the HF API rate-limits bursts
    raise RuntimeError(f"download failed {url}: {proc.stderr.strip()}")


def download_all() -> dict[str, str]:
    """Fetch every parquet file; return {relative path: sha256}."""
    hashes: dict[str, str] = {}
    for src in SOURCES:
        for split in src.splits:
            dest = DATA / "raw" / src.name / f"{split}.parquet"
            fetch(parquet_url(src.repo, split), dest)
            hashes[str(dest.relative_to(DATA))] = hashlib.sha256(dest.read_bytes()).hexdigest()
    return hashes


# ----------------------------------------------------------------------------- normalising
_URL = re.compile(r"(https?://\S+|www\.\S+|\b\S+\.(com|in|net|org|co|ly|io)\S*)", re.I)
_MAIL = re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.]+\b")
_DIGIT = re.compile(r"\d")
_NONWORD = re.compile(r"[^\w]+", re.UNICODE)


def clean(text: str) -> str:
    """NFKC, strip control chars, collapse whitespace. Content is never rewritten."""
    text = unicodedata.normalize("NFKC", str(text))
    text = "".join(ch for ch in text if ch == "\n" or unicodedata.category(ch)[0] != "C")
    return re.sub(r"\s+", " ", text).strip()


def template_key(text: str) -> str:
    t = text.lower()
    t = _MAIL.sub(" mailtok ", t)
    t = _URL.sub(" urltok ", t)
    t = _DIGIT.sub("0", t)
    t = _NONWORD.sub(" ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return hashlib.sha1(t.encode("utf-8")).hexdigest()[:16]


def _label(value: object, positive: tuple[str, ...]) -> int:
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return int(value)
    return int(str(value).strip().lower() in positive)


def load_source(src: Source) -> list[dict[str, object]]:
    import pandas as pd

    rows: list[dict[str, object]] = []
    for split in src.splits:
        df = pd.read_parquet(DATA / "raw" / src.name / f"{split}.parquet")
        if src.name == "phish_email":
            texts, labels = (
                df["Email Text"],
                [_label(v, ("phishing email",)) for v in df["Email Type"]],
            )
            langs = ["en"] * len(df)
        elif src.name == "clair_fraud":
            texts = df["text"]
            labels = [
                _label(v, ("fraud", "fraudulent", "1", "spam", "phishing")) for v in df["label"]
            ]
            langs = ["en"] * len(df)
        elif src.name == "uci_sms":
            texts, labels = df["message"], [_label(v, ("spam",)) for v in df["label"]]
            langs = ["en"] * len(df)
        elif src.name == "india_sms":
            texts, labels, langs = df["text"], [int(v) for v in df["label"]], ["en/hi"] * len(df)
        elif src.name == "india_14lang":
            texts = df["text"]
            labels = [int(v) for v in df["label"]]
            langs = [str(v) for v in df["language"]]
        elif src.name == "hinglish_calls":
            texts, labels, langs = df["text"], [int(v) for v in df["label"]], ["hinglish"] * len(df)
        elif src.name == "scam_dialogue":
            texts, labels, langs = df["dialogue"], [int(v) for v in df["label"]], ["en"] * len(df)
        else:  # pragma: no cover
            raise ValueError(src.name)
        split_name = {"validation": "val"}.get(split, split)
        for text, label, lang in zip(texts, labels, langs, strict=True):
            if text is None:
                continue
            t = clean(str(text))
            if len(t) < 3:
                continue
            rows.append(
                {
                    "text": t,
                    "label": int(label),
                    "lang": lang,
                    "dataset": src.name,
                    "channel": src.channel,
                    "official": split_name,
                }
            )
    return rows


def build_splits(
    src: Source, rows: list[dict[str, object]]
) -> tuple[list[dict[str, object]], dict]:
    """Dedup by template; assign train/val/test by template group. Returns (rows, stats)."""
    stats: dict[str, object] = {"raw": len(rows)}
    if src.official_split:
        raw_train = {template_key(str(r["text"])) for r in rows if r["official"] == "train"}
        stats["official_test_rows_sharing_a_train_template"] = sum(
            1 for r in rows if r["official"] == "test" and template_key(str(r["text"])) in raw_train
        )
        stats["official_test_rows"] = sum(1 for r in rows if r["official"] == "test")
    seen: set[str] = set()
    uniq = []
    for r in rows:
        r["group"] = template_key(str(r["text"]))
        key = f"{r['group']}|{r['label']}"
        if key in seen:
            continue
        seen.add(key)
        uniq.append(r)
    # A template labelled both ways is ambiguous: drop it entirely (it cannot be evaluated).
    by_group: dict[str, set[int]] = {}
    for r in uniq:
        by_group.setdefault(str(r["group"]), set()).add(int(r["label"]))  # type: ignore[arg-type]
    conflict = {g for g, labs in by_group.items() if len(labs) > 1}
    uniq = [r for r in uniq if r["group"] not in conflict]
    stats.update(
        {"after_template_dedup": len(uniq), "conflicting_templates_dropped": len(conflict)}
    )

    rng = random.Random(f"{SEED}:{src.name}")
    if src.official_split:
        train_groups = {r["group"] for r in uniq if r["official"] == "train"}
        out = []
        leaked = 0
        for r in uniq:
            if r["official"] in ("test",):
                if r["group"] in train_groups:
                    leaked += 1
                    continue
                r["split"] = "test"
            elif r["official"] == "val":
                if r["group"] in train_groups:
                    continue
                r["split"] = "val"
            else:
                r["split"] = "train"
            out.append(r)
        if not any(r["split"] == "val" for r in out):
            # carve 15% of train groups as validation
            groups = sorted({r["group"] for r in out if r["split"] == "train"})
            rng.shuffle(groups)
            val = set(groups[: int(0.15 * len(groups))])
            for r in out:
                if r["split"] == "train" and r["group"] in val:
                    r["split"] = "val"
        stats["official_test_rows_dropped_as_train_template"] = leaked
        uniq = out
    else:
        groups = sorted({r["group"] for r in uniq})
        rng.shuffle(groups)
        n = len(groups)
        cut1, cut2 = int(0.70 * n), int(0.85 * n)
        where = {
            g: ("train" if i < cut1 else "val" if i < cut2 else "test")
            for i, g in enumerate(groups)
        }
        for r in uniq:
            r["split"] = where[str(r["group"])]
    for sp in ("train", "val", "test"):
        part = [r for r in uniq if r["split"] == sp]
        stats[sp] = {"n": len(part), "fraud": sum(int(r["label"]) for r in part)}  # type: ignore[arg-type]
    return uniq, stats


def build_all() -> tuple[list[dict[str, object]], dict[str, object]]:
    rows: list[dict[str, object]] = []
    stats: dict[str, object] = {}
    for src in SOURCES:
        part, st = build_splits(src, load_source(src))
        rows += part
        stats[src.name] = st
    return rows, stats


def save_table(rows: list[dict[str, object]]) -> Path:
    import pandas as pd

    out = DATA / "table.parquet"
    pd.DataFrame(rows).to_parquet(out, index=False)
    return out


def main() -> None:
    hashes = download_all()
    rows, stats = build_all()
    path = save_table(rows)
    manifest = {
        "seed": SEED,
        "sources": [
            {
                "name": s.name,
                "repo": s.repo,
                "licence": s.licence,
                "channel": s.channel,
                "official_split": s.official_split,
                "synthetic": s.synthetic,
                "note": s.note,
            }
            for s in SOURCES
        ],
        "files_sha256": hashes,
        "split_stats": stats,
        "table_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }
    (ROOT / "results" / "text_eval_manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    print(json.dumps(stats, indent=1))


if __name__ == "__main__":
    main()


