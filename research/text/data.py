"""Open fraud-text datasets for the text benchmark: download, normalise, deduplicate, split.

Every set is public on Hugging Face under an open licence; files are pinned by sha256 in
results/text_eval_manifest.json and stored OUTSIDE the repo ($SATYAPAN_TEXT_DATA, default
../satyapan-data/text). Nothing here is synthetic except where the source says so (the
"synthetic" flag below), and that generation code belongs to the dataset's authors.

Unified record: text, label (1 = fraud/scam/phishing, 0 = legitimate), group (template id for
leakage-safe splitting), split (train/val/test), dataset, language, channel.

Leakage control: SMS and email corpora are full of templated near-duplicates that differ only
in numbers, names or links. `template_key` maps a text to its template (lower-case, digits ->
0, URLs/emails -> tokens, punctuation and spaces collapsed). Exact-template duplicates are
dropped, and splits are made by template group, so no template sits in both train and test.
Where a dataset ships official splits we keep them, drop test rows whose template also occurs
in train ("dedup-test"), and report how many were dropped.
"""

